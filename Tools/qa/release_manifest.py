"""Release manifest (spec §19 Gate 5: "preserved source/asset hashes").

Hashes every file of the player build (Builds/Game, without Unity's do-not-ship debug folder and logs) and every content
document the game and the control plane load (Assets/Content/Data/**/*.json, each course's route.json), and records the
source revision: the repository HEAD, the last commit that changed Assets/, ProjectSettings/ or Packages/, and whether
those folders have uncommitted changes now. Writes Evidence/release/build-manifest.json (full lists) and
build-manifest.md (summary).

It states what the build IS, byte for byte. It does not prove which revision produced it (Unity builds are not
bit-reproducible here); a release build should be made from a clean checkout of the recorded revision and its manifest
taken straight after.

    py Tools/qa/release_manifest.py
"""
import datetime
import hashlib
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUILD = os.path.join(ROOT, "Builds", "Game")
OUT = os.path.join(ROOT, "Evidence", "release")
NOT_SHIPPED = ("_BackUpThisFolder_ButDontShipItWithYourGame",)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def listing(base, keep):
    rows = []
    for root, dirs, files in os.walk(base):
        dirs[:] = sorted(d for d in dirs if not any(m in d for m in NOT_SHIPPED))
        for name in sorted(files):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, ROOT).replace("\\", "/")
            if keep(rel):
                rows.append({"path": rel, "bytes": os.path.getsize(path), "sha256": sha256(path)})
    return rows


def aggregate(rows):
    h = hashlib.sha256()
    for r in sorted(rows, key=lambda r: r["path"]):
        h.update(f"{r['sha256']}  {r['path']}\n".encode("utf-8"))
    return h.hexdigest()


def main():
    if not os.path.isdir(BUILD):
        raise SystemExit("no player build at Builds/Game")
    build = listing(BUILD, lambda rel: not rel.endswith(".log"))
    content = listing(os.path.join(ROOT, "Assets", "Content", "Data"), lambda rel: rel.endswith(".json"))
    content += listing(os.path.join(ROOT, "Assets", "Content", "Courses"), lambda rel: rel.endswith("/route.json"))
    runtime = os.path.join(BUILD, "NightSignal_Data", "Managed", "NightSignal.Runtime.dll")
    built = datetime.datetime.fromtimestamp(os.path.getmtime(runtime)).isoformat(timespec="seconds")
    source_dirs = ["Assets", "ProjectSettings", "Packages"]
    manifest = {
        "schema": "night-signal/build-manifest@1",
        "generatedLocal": datetime.datetime.now().isoformat(timespec="seconds"),
        "head": git("rev-parse", "HEAD"),
        "lastSourceCommit": git("log", "-1", "--format=%H", "--", *source_dirs),
        "lastSourceCommitTime": git("log", "-1", "--format=%cI", "--", *source_dirs),
        "sourceUncommittedNow": [l for l in git("status", "--porcelain", "--", *source_dirs).splitlines()
                                 if "LiberationSans" not in l and "_Recovery" not in l],
        "playerBuiltLocal": built,
        "build": {"files": len(build), "bytes": sum(r["bytes"] for r in build), "aggregateSha256": aggregate(build), "list": build},
        "content": {"files": len(content), "bytes": sum(r["bytes"] for r in content), "aggregateSha256": aggregate(content), "list": content},
    }
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "build-manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=1)
        f.write("\n")
    biggest = sorted(build, key=lambda r: -r["bytes"])[:5]
    md = [
        "# Build manifest (spec §19 Gate 5: preserved source/asset hashes)",
        "",
        "Generated by `Tools/qa/release_manifest.py`. It records what the build is, byte for byte; it does not prove which",
        "revision produced it (see the tool's header).",
        "",
        f"- Repository HEAD: `{manifest['head']}`",
        f"- Last commit changing Assets/, ProjectSettings/, Packages/: `{manifest['lastSourceCommit']}` ({manifest['lastSourceCommitTime']})",
        f"- Uncommitted changes in those folders now (TMP font atlases and the crash-recovery scene excluded): "
        + ("none" if not manifest["sourceUncommittedNow"] else ", ".join(manifest["sourceUncommittedNow"])),
        f"- Player build (`Builds/Game`, Unity's do-not-ship debug folder and logs excluded): {len(build)} files, "
        f"{manifest['build']['bytes'] / 1e6:.1f} MB, built {built} (local time); aggregate sha256 `{manifest['build']['aggregateSha256']}`",
        f"- Content documents (Assets/Content/Data/**/*.json and each course's route.json): {len(content)} files, "
        f"aggregate sha256 `{manifest['content']['aggregateSha256']}`",
        "",
        "Largest build files:",
        "",
    ]
    md += [f"- `{r['path']}` {r['bytes'] / 1e6:.1f} MB `{r['sha256'][:16]}…`" for r in biggest]
    md += ["", "The full per-file lists are in `build-manifest.json`."]
    with open(os.path.join(OUT, "build-manifest.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    print(f"build {len(build)} files {manifest['build']['aggregateSha256'][:16]}; content {len(content)} files {manifest['content']['aggregateSha256'][:16]}")


if __name__ == "__main__":
    main()
